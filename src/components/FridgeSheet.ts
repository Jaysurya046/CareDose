import { medStore } from '../store/medStore';

export function renderFridgeSheet(container: HTMLElement) {
  const profile = medStore.getPatientProfile();
  const activeMeds = medStore.getActiveMedications();

  const printDate = new Date().toLocaleDateString(undefined, {
    month: 'long',
    day: 'numeric',
    year: 'numeric'
  });

  container.innerHTML = `
    <div class="fridge-sheet-container">
      <!-- On-screen Control Action Bar (Hidden during print) -->
      <div class="fridge-toolbar card no-print">
        <div class="toolbar-title-group">
          <div>
            <h2 style="font-size: 1.25rem; font-weight: 700;">Emergency Medical & Fridge Sheet</h2>
            <p style="font-size: 0.875rem; color: var(--text-muted);">
              Formatted according to EMS guidelines. Print and affix to the primary home refrigerator door.
            </p>
          </div>
        </div>

        <div class="toolbar-actions">
          <button type="button" class="btn btn-secondary" id="btn-edit-patient">
            <svg width="18" height="18" viewBox="0 0 24 24" fill="none" stroke="currentColor" stroke-width="2">
              <path d="M11 4H4a2 2 0 0 0-2 2v14a2 2 0 0 0 2 2h14a2 2 0 0 0 2-2v-7"/>
              <path d="M18.5 2.5a2.121 2.121 0 0 1 3 3L12 15l-4 1 1-4 9.5-9.5z"/>
            </svg>
            <span>Edit Patient Info</span>
          </button>

          <button type="button" class="btn btn-primary" id="btn-print-sheet">
            <svg width="18" height="18" viewBox="0 0 24 24" fill="none" stroke="currentColor" stroke-width="2.5">
              <polyline points="6 9 6 2 18 2 18 9"/>
              <path d="M6 18H4a2 2 0 0 1-2-2v-5a2 2 0 0 1 2-2h16a2 2 0 0 1 2 2v5a2 2 0 0 1-2 2h-2"/>
              <rect x="6" y="14" width="12" height="8"/>
            </svg>
            <span>Print Emergency Sheet</span>
          </button>
        </div>
      </div>

      <!-- Printable Document Canvas -->
      <div class="fridge-document card" id="printable-fridge-area">
        <div class="print-header">
          <div>
            <h1>Emergency Medical Information</h1>
            <p style="font-size: 0.875rem; color: #475569; margin-top: 2px;">
              Generated by CareDose • Current as of ${printDate}
            </p>
          </div>
          <div class="emergency-callout">
            ATTN: PARAMEDICS / EMS / ER
          </div>
        </div>

        <!-- Patient Demographics Grid -->
        <div class="print-patient-grid">
          <div>
            <span class="field-label">Patient Full Name</span>
            <span class="field-value" style="font-size: 1.25rem;">${profile.name}</span>
          </div>
          <div>
            <span class="field-label">Date of Birth</span>
            <span class="field-value">${profile.dob}</span>
          </div>
          <div>
            <span class="field-label">Blood Type</span>
            <span class="field-value">${profile.bloodType || 'Unknown'}</span>
          </div>
        </div>

        <!-- High-Risk Allergies Box -->
        <div class="print-allergies-box">
          <div class="allergy-title">⚠️ Known Drug Allergies & Adverse Reactions</div>
          <div class="allergy-list">
            ${profile.allergies.length > 0 
              ? profile.allergies.join(' • ') 
              : 'No known drug allergies reported (NKDA)'}
          </div>
        </div>

        <!-- Active Medications Table -->
        <h3 style="font-size: 1rem; text-transform: uppercase; font-weight: 800; margin-bottom: 0.5rem;">
          Current Active Medications (${activeMeds.length})
        </h3>
        <table class="print-table" aria-label="Active Medication Schedule Table">
          <thead>
            <tr>
              <th scope="col">Medication & Strength</th>
              <th scope="col">Form</th>
              <th scope="col">Daily Timing</th>
              <th scope="col">Special Instructions</th>
              <th scope="col">Prescribed By</th>
            </tr>
          </thead>
          <tbody>
            ${activeMeds.length > 0 ? activeMeds.map(m => `
              <tr>
                <td>
                  <strong>${m.name}</strong> <span>${m.dosage}</span>
                  ${m.genericName ? `<br><small style="color: #475569;">(${m.genericName})</small>` : ''}
                </td>
                <td>${m.form}</td>
                <td><strong>${m.timeSlots.map(s => s.toUpperCase()).join(', ')}</strong></td>
                <td>
                  ${m.withFood ? '<strong>[Take with food]</strong> ' : ''}
                  ${m.instructions}
                </td>
                <td>${m.prescribedBy || 'N/A'}</td>
              </tr>
            `).join('') : `
              <tr>
                <td colspan="5" style="text-align: center; padding: 1rem;">No active medications currently registered.</td>
              </tr>
            `}
          </tbody>
        </table>

        <!-- Emergency Contacts Footer -->
        <div class="print-footer-grid">
          <div class="print-footer-box">
            <h4>Primary Emergency Contact</h4>
            <p><strong>${profile.emergencyContactName}</strong> (${profile.emergencyContactRelation})</p>
            <p style="font-size: 1.1rem; font-weight: 700; margin-top: 3px;">${profile.emergencyContactPhone}</p>
          </div>

          <div class="print-footer-box">
            <h4>Primary Physician & Clinic</h4>
            <p><strong>${profile.primaryDoctorName}</strong></p>
            <p style="font-size: 1.1rem; font-weight: 700; margin-top: 3px;">${profile.primaryDoctorPhone}</p>
            <p style="font-size: 0.85rem; color: #475569;">Preferred Hospital: ${profile.preferredHospital}</p>
          </div>
        </div>

        ${profile.notes ? `
          <div style="margin-top: 8pt; border: 1pt solid #000; padding: 6pt;">
            <span class="field-label">Special Medical Notes / Mobility / Devices:</span>
            <p style="margin: 2pt 0 0 0; font-size: 9.5pt;">${profile.notes}</p>
          </div>
        ` : ''}

        <p class="print-disclaimer">
          Notice: This emergency sheet is compiled by the patient or family caregiver for rapid reference. Medical personnel should confirm active regimens through clinical health systems where available.
        </p>
      </div>
    </div>
  `;

  // Print button handler
  container.querySelector('#btn-print-sheet')?.addEventListener('click', () => {
    window.print();
  });

  // Edit Patient Info Modal handler
  container.querySelector('#btn-edit-patient')?.addEventListener('click', () => {
    openPatientEditModal(() => renderFridgeSheet(container));
  });
}

function openPatientEditModal(onSaved: () => void) {
  document.querySelector('.modal-overlay')?.remove();
  const profile = medStore.getPatientProfile();

  const modalOverlay = document.createElement('div');
  modalOverlay.className = 'modal-overlay';
  modalOverlay.innerHTML = `
    <div class="modal-dialog">
      <div class="modal-header">
        <h3 style="font-size: 1.25rem; font-weight: 700;">Edit Patient & Emergency Info</h3>
        <button type="button" class="btn btn-secondary btn-sm" id="btn-close-patient-modal">✕</button>
      </div>

      <form id="patient-form" class="modal-body">
        <div style="display: grid; grid-template-columns: 2fr 1fr; gap: 1rem;">
          <div class="form-group">
            <label class="form-label" for="pat-name">Patient Full Name *</label>
            <input type="text" id="pat-name" class="form-input" value="${profile.name}" required />
          </div>
          <div class="form-group">
            <label class="form-label" for="pat-blood">Blood Type</label>
            <input type="text" id="pat-blood" class="form-input" value="${profile.bloodType}" placeholder="e.g. A+" />
          </div>
        </div>

        <div class="form-group">
          <label class="form-label" for="pat-dob">Date of Birth</label>
          <input type="date" id="pat-dob" class="form-input" value="${profile.dob}" />
        </div>

        <div class="form-group">
          <label class="form-label" for="pat-allergies">Known Drug Allergies (Comma separated) *</label>
          <input type="text" id="pat-allergies" class="form-input" value="${profile.allergies.join(', ')}" placeholder="e.g. Penicillin, Sulfa, Aspirin" />
          <span class="form-hint">Crucial for emergency personnel. Enter "None" if no known allergies.</span>
        </div>

        <div style="display: grid; grid-template-columns: 1fr 1fr; gap: 1rem;">
          <div class="form-group">
            <label class="form-label" for="pat-em-name">Emergency Contact Name</label>
            <input type="text" id="pat-em-name" class="form-input" value="${profile.emergencyContactName}" />
          </div>
          <div class="form-group">
            <label class="form-label" for="pat-em-rel">Relationship</label>
            <input type="text" id="pat-em-rel" class="form-input" value="${profile.emergencyContactRelation}" placeholder="e.g. Daughter, Spouse" />
          </div>
        </div>

        <div class="form-group">
          <label class="form-label" for="pat-em-phone">Emergency Contact Phone *</label>
          <input type="tel" id="pat-em-phone" class="form-input" value="${profile.emergencyContactPhone}" required />
        </div>

        <div style="display: grid; grid-template-columns: 1fr 1fr; gap: 1rem;">
          <div class="form-group">
            <label class="form-label" for="pat-doc-name">Primary Doctor Name</label>
            <input type="text" id="pat-doc-name" class="form-input" value="${profile.primaryDoctorName}" />
          </div>
          <div class="form-group">
            <label class="form-label" for="pat-doc-phone">Doctor Office Phone</label>
            <input type="tel" id="pat-doc-phone" class="form-input" value="${profile.primaryDoctorPhone}" />
          </div>
        </div>

        <div class="form-group">
          <label class="form-label" for="pat-hospital">Preferred Hospital</label>
          <input type="text" id="pat-hospital" class="form-input" value="${profile.preferredHospital}" />
        </div>

        <div class="form-group">
          <label class="form-label" for="pat-notes">Special Medical Notes / Devices</label>
          <textarea id="pat-notes" class="form-textarea" placeholder="e.g. Pacemaker, diabetic, uses walker, hard of hearing">${profile.notes}</textarea>
        </div>

        <div class="modal-footer">
          <button type="button" class="btn btn-secondary" id="btn-cancel-pat">Cancel</button>
          <button type="submit" class="btn btn-primary">Save Information</button>
        </div>
      </form>
    </div>
  `;

  document.body.appendChild(modalOverlay);

  const close = () => modalOverlay.remove();
  modalOverlay.querySelector('#btn-close-patient-modal')?.addEventListener('click', close);
  modalOverlay.querySelector('#btn-cancel-pat')?.addEventListener('click', close);

  const form = modalOverlay.querySelector('#patient-form') as HTMLFormElement;
  form.addEventListener('submit', (e) => {
    e.preventDefault();
    const allergiesStr = (modalOverlay.querySelector('#pat-allergies') as HTMLInputElement).value;
    const allergies = allergiesStr
      .split(',')
      .map(s => s.trim())
      .filter(s => s.length > 0);

    medStore.updateProfile({
      name: (modalOverlay.querySelector('#pat-name') as HTMLInputElement).value.trim(),
      bloodType: (modalOverlay.querySelector('#pat-blood') as HTMLInputElement).value.trim(),
      dob: (modalOverlay.querySelector('#pat-dob') as HTMLInputElement).value,
      allergies,
      emergencyContactName: (modalOverlay.querySelector('#pat-em-name') as HTMLInputElement).value.trim(),
      emergencyContactRelation: (modalOverlay.querySelector('#pat-em-rel') as HTMLInputElement).value.trim(),
      emergencyContactPhone: (modalOverlay.querySelector('#pat-em-phone') as HTMLInputElement).value.trim(),
      primaryDoctorName: (modalOverlay.querySelector('#pat-doc-name') as HTMLInputElement).value.trim(),
      primaryDoctorPhone: (modalOverlay.querySelector('#pat-doc-phone') as HTMLInputElement).value.trim(),
      preferredHospital: (modalOverlay.querySelector('#pat-hospital') as HTMLInputElement).value.trim(),
      notes: (modalOverlay.querySelector('#pat-notes') as HTMLTextAreaElement).value.trim()
    });

    close();
    onSaved();
  });
}
